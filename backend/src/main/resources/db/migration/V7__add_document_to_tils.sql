-- TIL 을 두 형식으로 저장한다.
--
--   content            기획서의 6항목 TIL (오늘 배운 내용 / 핵심 개념 / 실습 내용 /
--                      새롭게 알게 된 점 / 어려웠던 점 / 오늘의 회고) — 학습 기록 그 자체
--   document_markdown  목차와 주제별 섹션(표·코드블록)으로 구성한 긴 문서 —
--                      velog·티스토리에 그대로 붙여넣는 용도
--
-- 한 컬럼에 몰아넣지 않는 이유는 쓰임이 다르기 때문이다. 목록·복습 알림은 짧은 기록을,
-- 공유는 긴 문서를 쓴다. 기존 행과 문서를 만들지 않은 TIL 이 있을 수 있어 NULL 을 허용한다.
ALTER TABLE tils ADD COLUMN document_markdown text;
